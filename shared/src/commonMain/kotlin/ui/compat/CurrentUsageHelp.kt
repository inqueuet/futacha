private fun renderCurrentHelpSection(id: String, title: String, sections: List<Pair<String, String>>) = buildString {
    append("<label for=\"$id\" class=\"index\">$title</label>")
    append("<input type=\"checkbox\" id=\"$id\" class=\"on-off\" />")
    append("<div class=\"explain\">")
    sections.forEach { (heading, body) -> append("<p class=\"title\">$heading</p><p class=\"explain\">$body</p>") }
    append("</div>")
}

